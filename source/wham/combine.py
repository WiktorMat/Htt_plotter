import shutil
import subprocess
import tempfile
import time
from pathlib import Path
from typing import Any

import numpy as np

from wham import __version__, util
from wham.config import AnalysisConfig
from wham.fitconfig import (
    FitConfig,
    ScanCfg,
    datacard_processes,
    dc_name,
    scale_map,
    syst_matches,
    template_parents,
    translate_formula,
)

SHAPES_FILE = "shapes.root"
DATACARD_FILE = "datacard.txt"
WORKSPACE_FILE = "workspace.root"
MODEL_FILE = "whammodel.py"
FITRESULT_FILE = "fitresult.json"
DUMP_SCRIPT_FILE = "dump_fitresult.py"


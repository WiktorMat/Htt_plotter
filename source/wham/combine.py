def ch_backend(fit: FitConfig) -> bool:
    """A fit with a TES morph uses the CombineHarvester/cmsenv backend (see the
    module docstring for why standalone combine cannot do morph + autoMCStats)."""
    return bool(fit.model.morphs)


def cmssw_base(fit: FitConfig) -> str:
    """Resolve the CMSSW release for the CH backend; required, no default path."""
    base = fit.combine.cmssw
    if not base:
        raise ValueError(
            f"fit '{fit.name}' has a TES morph, which needs CombineHarvester from a "
            "CMSSW release, but combine.cmssw is unset. Add e.g.\n"
            "  combine:\n    cmssw: /afs/.../CMSSW_14_1_0_pre4\n"
            "to the fit config (see Configurations/tau_sf/README.md)."
        )
    if not (Path(base) / "src").is_dir():
        raise FileNotFoundError(f"combine.cmssw '{base}' has no src/ — not a CMSSW release")
    return base


# Generated CombineHarvester driver: reads WHAM's shapes.root directly (numeric
# $PROCESS_TES$MASS templates), builds the per-DM datacard with the morphed signal
# as a CMSHistFunc (getXVar -> autoMCStats works), and writes datacard + shapes.
_HARVEST_TEMPLATE = '''"""Generated by wham: CombineHarvester datacard for fit '{name}'.

The morphed signal is built as a combine-native CMSHistFunc via
BuildCMSHistFuncFactory, the one morph that implements getXVar(), so autoMCStats
(bin-by-bin stats -> one-to-one postfit) can stay on. Runs under cmsenv."""
import ROOT
from CombineHarvester.CombineTools import ch
from CombineHarvester.CombinePdfs.morphing import BuildCMSHistFuncFactory

ROOT.gROOT.SetBatch(True)
ROOT.RooMsgService.instance().setGlobalKillBelow(ROOT.RooFit.ERROR)

SHAPES = "{shapes}"
BINS = {bins}            # [[idx, name], ...]
BKG = {bkg}              # {{bin: [process, ...]}} present (nonzero) backgrounds
SIGNAL = "{signal}"      # the morphed signal process (datacard-safe name)
MASSES = {masses}        # TES grid as strings, e.g. ["0.950", ..., "1.050"]
TES = "{tes}"            # tes POI name
TES_RANGE = {tes_range}  # [lo, hi]
LNN = {lnn}              # [{{name, sf, bins, procs}}, ...]
SHAPESYS = {shapesys}    # [{{name, bins, procs}}, ...]
RATEPARAMS = {rateparams}  # [{{name, bin, proc, init, range}}, ...]
AUTOMCSTATS = {automcstats}  # int threshold, or None to disable

ana, era, chan = ["wham"], ["13p6TeV"], ["mt"]
cats = [(i, n) for i, n in BINS]

cb = ch.CombineHarvester()
cb.AddObservations(["*"], ana, era, chan, cats)
for i, n in BINS:                       # backgrounds vary per bin
    procs = BKG.get(n, [])
    if procs:
        cb.AddProcesses(["*"], ana, era, chan, procs, [(i, n)], False)
cb.AddProcesses(MASSES, ana, era, chan, [SIGNAL], cats, True)  # morphed signal

for s in LNN:
    cb.cp().bin(s["bins"]).process(s["procs"]).AddSyst(
        cb, s["name"], "lnN", ch.SystMap()(s["sf"]))
for s in SHAPESYS:
    cb.cp().bin(s["bins"]).process(s["procs"]).AddSyst(
        cb, s["name"], "shape", ch.SystMap()(1.0))
for r in RATEPARAMS:
    cb.cp().bin([r["bin"]]).process([r["proc"]]).AddSyst(
        cb, r["name"], "rateParam", ch.SystMap()(r["init"]))

cb.cp().backgrounds().ExtractShapes(SHAPES, "$BIN/$PROCESS", "$BIN/$PROCESS_$SYSTEMATIC")
cb.cp().signals().ExtractShapes(SHAPES, "$BIN/$PROCESS_TES$MASS", "$BIN/$PROCESS_$SYSTEMATIC")

for r in RATEPARAMS:                    # bounds after the params exist
    p = cb.GetParameter(r["name"])
    if r["range"] is not None:
        p.set_range(r["range"][0], r["range"][1])
    p.set_val(r["init"])

# Continuous TES morph as a CMSHistFunc over the grid, shared tes parameter.
ws = ROOT.RooWorkspace("morph", "morph")
tes = ROOT.RooRealVar(TES, TES, 1.0, TES_RANGE[0], TES_RANGE[1])
tes.setConstant(True)                   # --redefineSignalPOIs frees it at fit time
BuildCMSHistFuncFactory(ws, cb, tes, SIGNAL)  # signal morphs; backgrounds -> static CMSHistFunc
cb.AddWorkspace(ws, False)
# Every process now has a workspace function ($BIN_$PROCESS_morph); pointing all
# of them at the ws (full cb, not just the signal) gives one wildcard shapes line
# and avoids the leftover-TH1 / duplicate-FAKE-line clash.
cb.ExtractPdfs(cb, "morph", "$BIN_$PROCESS_morph", "")
cb.ExtractData("morph", "$BIN_data_obs")  # use ws data_obs (avoid duplicate line)

if AUTOMCSTATS is not None:
    cb.SetAutoMCStats(cb, AUTOMCSTATS, 1, 1)

cb.WriteDatacard("{datacard}", "{ch_shapes}")
print("harvest: wrote {datacard} (%d bins, %d masses)" % (len(BINS), len(MASSES)))
'''


def harvest_source(
    fit: FitConfig,
    cfg: AnalysisConfig,
    present: dict[str, set[str]],
    parents: dict[str, str],
    shape_affected_map: dict[str, set[str]] | None = None,
    datacard: str = DATACARD_FILE,
) -> str:
    """Generate the cmsenv CombineHarvester driver for a morph fit.

    `present[bin]` is the set of datacard process names actually written for that
    bin (zero-yield backgrounds are dropped), so the CH model matches the shapes.
    Only the bare-POI scales + single TES morph used by the SF measurement are
    supported (a formula scale would need a PhysicsModel, which CH does not run).
    Control categories are excluded — they are merged in later at the datacard
    level (combineCards.py), so `datacard` is HARVEST_CARD_FILE in that case.
    """
    if "r" in all_pois(fit):
        raise ValueError(
            "CH backend reserves the POI name 'r' for the default signal strength "
            "(frozen at 1); rename the model POI (e.g. tid_SF_...)"
        )
    if len(fit.model.morphs) != 1:
        raise NotImplementedError(
            "CH backend supports exactly one morph (TES) per fit; "
            f"'{fit.name}' has {len(fit.model.morphs)}"
        )
    mname, morph = next(iter(fit.model.morphs.items()))
    signal = dc_name(morph.process)
    signal_names, background_names = datacard_processes(fit, cfg)
    if signal_names != [signal]:
        raise NotImplementedError(
            "CH backend requires the morphed process to be the only model process "
            f"(model templates {signal_names}, morph process '{signal}')"
        )

    cats = [c.name for c in main_categories(fit)]
    bins = [[i, c] for i, c in enumerate(cats)]
    bkg = {c: [b for b in background_names if b in present.get(c, set())] for c in cats}
    masses = [f"{f:.3f}" for f in grid_points(morph.grid)]
    all_dc = signal_names + background_names

    def present_in(cat: str, name: str) -> bool:
        return name in present.get(cat, set())

    lnn, shapesys = [], []
    for syst in fit.systematics:
        # control bins live in the separate control card, not in CH
        sbins = [b for b in (syst.categories if syst.categories is not None else cats)
                 if b in cats]
        if syst.effect == "lnN":
            procs = sorted({
                n for c in sbins for n in all_dc
                if present_in(c, n) and syst_matches(syst.processes, n, parents.get(n))
            })
            if procs:
                lnn.append({"name": syst.name, "sf": syst.scaleFactor,
                            "bins": sbins, "procs": procs})
        elif syst.effect == "shape":
            affected = (shape_affected_map or {}).get(syst.name, set())
            procs = sorted({
                n for c in sbins for n in all_dc
                if present_in(c, n) and parents.get(n, n) in affected
            })
            if procs:
                shapesys.append({"name": syst.name, "bins": sbins, "procs": procs})

    rateparams: list[dict] = []
    # bare-POI per-(bin, process) yield scales become rateParams (the ID SFs)
    for cat, template, expr in scale_entries(fit):
        e = expr.strip()
        if e not in fit.model.pois:
            raise NotImplementedError(
                f"CH backend supports only bare-POI scales; got '{expr}' on '{template}' "
                "(a formula scale needs a PhysicsModel, unavailable under CH)"
            )
        pcfg = fit.model.pois[e]
        for b in (cats if cat is None else [cat]):
            if present_in(b, template):
                rateparams.append({"name": e, "bin": b, "proc": template,
                                   "init": pcfg.init, "range": list(pcfg.range)})
    # explicit rateParam systematics (free normalizations)
    for syst in fit.systematics:
        if syst.effect != "rateParam":
            continue
        sbins = [b for b in (syst.categories if syst.categories is not None else cats)
                 if b in cats]
        rng = list(syst.range) if syst.range else None
        for c in sbins:
            for n in all_dc:
                if present_in(c, n) and syst_matches(syst.processes, n, parents.get(n)):
                    rateparams.append({"name": syst.name, "bin": c, "proc": n,
                                       "init": syst.init, "range": rng})

    return _HARVEST_TEMPLATE.format(
        name=fit.name, shapes=SHAPES_FILE, datacard=datacard, ch_shapes=CH_SHAPES_FILE,
        bins=repr(bins), bkg=repr(bkg), signal=repr(signal)[1:-1],
        masses=repr(masses), tes=mname, tes_range=repr(list(morph.range)),
        lnn=repr(lnn), shapesys=repr(shapesys), rateparams=repr(rateparams),
        automcstats=repr(fit.auto_mc_stats),
    )


# ------------------------------------------------------------- templates


def _slice1d(h: Any, process: str, region: str, variation: str = "nominal"):
    return h[{"process": process, "region": region, "variation": variation}].copy()


def _clip_negative(h1, label: str, console=None) -> None:
    view = h1.view()
    neg = view["value"] < 0
    if np.any(neg):
        if console is not None:
            console.print(f"  [yellow]clipped {int(neg.sum())} negative bins in {label}[/yellow]")
        view["value"][neg] = 0.0


def inject_toy_asymmetry(first_h, second_h, asymmetry: float) -> None:
    """Modulate two templates by (1 +- A*cos(x)) in place — yield-preserving toy."""
    centers = first_h.axes[0].centers
    for h1, sign in ((first_h, +1.0), (second_h, -1.0)):
        view = h1.view()
        factor = 1.0 + sign * asymmetry * np.cos(centers)
        before = view["value"].sum()
        view["value"] *= factor
        view["variance"] *= factor**2
        after = view["value"].sum()
        if after > 0:
            view["value"] *= before / after
            view["variance"] *= (before / after) ** 2


def fit_templates(
    fit: FitConfig, cfg: AnalysisConfig, hists_by_cat: dict[str, dict], console=None,
    cat_cfgs: dict[str, AnalysisConfig] | None = None,
) -> tuple[dict[str, dict[str, Any]], list[str], list[str]]:
    """Build datacard templates for every category.

    Returns (templates, signal_names, background_names) where templates is
    {category: {datacard_name: 1D hist}} including 'data_obs'. Zero-yield
    backgrounds are dropped per category; background_names keeps the union.
    A control category slices its OWN analysis (`cat_cfgs`): its processes,
    data process, signal region and QCD estimate; never the model's
    scales/components/morph grids.
    """
    cat_cfgs = cat_cfgs or {}
    signal_names, backgrounds = union_datacard_processes(fit, cfg, cat_cfgs)

    templates: dict[str, dict[str, Any]] = {}
    for cat in fit.categories:
        ccfg = cat_cfgs.get(cat.name, cfg)
        region = signal_region(ccfg)
        shape_systs = [(s, shape_affected(fit, ccfg, s))
                       for s in fit.systematics if s.effect == "shape"]

        def shape_slices(cat_name: str, proc: str):
            """(syst, datacard suffix, variation label) triples for one process."""
            for syst, affected in shape_systs:
                if syst.categories is not None and cat_name not in syst.categories:
                    continue
                if proc not in affected:
                    continue
                yield from ((syst, f"{syst.name}Up", f"{syst.name}_up"),
                            (syst, f"{syst.name}Down", f"{syst.name}_down"))

        hists = hists_by_cat[cat.name]
        h_datamc = hists[("datamc", cat.variable)]
        t: dict[str, Any] = {
            "data_obs": _slice1d(h_datamc, ccfg.data_process(), region)
        }
        for proc in ccfg.stack_order():
            # the model acts in main-analysis bins only (a control process
            # sharing a model process name is rejected at load time)
            pm = fit.model.processes.get(proc) if cat.analysis is None else None
            if pm is None or pm.components is None:
                h1 = _slice1d(h_datamc, proc, region)
                _clip_negative(h1, f"{cat.name}/{proc}", console)
                if h1.view()["value"].sum() <= 0:
                    if pm is None:
                        if console is not None:
                            console.print(
                                f"  [yellow]dropping zero-yield background "
                                f"'{proc}' in '{cat.name}'[/yellow]"
                            )
                        continue
                    if console is not None:  # model process: keep, but warn
                        console.print(
                            f"  [yellow]model process '{proc}' has zero yield "
                            f"in '{cat.name}'[/yellow]"
                        )
                t[dc_name(proc)] = h1
                for _syst, suffix, vlabel in shape_slices(cat.name, proc):
                    hv = _slice1d(h_datamc, proc, region, vlabel)
                    _clip_negative(hv, f"{cat.name}/{proc} {suffix}", console)
                    t[f"{dc_name(proc)}_{suffix}"] = hv
            else:
                h_fitcp = hists[("fitcp", cat.variable)]
                comp_hists = []
                for comp in pm.components:
                    h1 = _slice1d(h_fitcp, proc, comp)
                    _clip_negative(h1, f"{cat.name}/{proc} {comp}", console)
                    comp_hists.append((comp, h1))
                if fit.toy.asymmetry != 0.0 and len(comp_hists) == 2:
                    inject_toy_asymmetry(comp_hists[0][1], comp_hists[1][1],
                                         fit.toy.asymmetry)
                for comp, h1 in comp_hists:
                    t[dc_name(f"{proc}_{comp}")] = h1
                for _syst, suffix, vlabel in shape_slices(cat.name, proc):
                    for comp in pm.components:
                        hv = _slice1d(h_fitcp, proc, comp, vlabel)
                        _clip_negative(hv, f"{cat.name}/{proc} {comp} {suffix}", console)
                        t[f"{dc_name(f'{proc}_{comp}')}_{suffix}"] = hv
        # TES grid templates: the morphed process refilled at each grid point
        # with its scaled columns — shape AND yield vary with f (scaled cuts
        # migrate events across category edges). CMSHistFunc interpolates the
        # template integrals linearly in f, so the yield slope enters the fit.
        for mname, morph in fit.model.morphs.items():
            if cat.name not in morph.categories:
                continue
            dcgen = dc_name(morph.process)
            yields: list[tuple[float, float]] = []
            for f in grid_points(morph.grid):
                vlabel = "nominal" if abs(f - 1.0) < 1e-9 else morph_point_label(mname, f)
                hg = _slice1d(h_datamc, morph.process, region, vlabel)
                _clip_negative(hg, f"{cat.name}/{dcgen} {mname} f={f}", console)
                total = float(hg.view()["value"].sum())
                if total <= 0:
                    # CMSHistFunc silently returns an EMPTY signal on any grid
                    # segment whose endpoint template has non-positive integral
                    raise ValueError(
                        f"morph '{mname}': grid template f={f} in '{cat.name}' "
                        f"has non-positive yield ({total:.4g})"
                    )
                yields.append((f, total))
                t[morph_template_name(dcgen, mname, f)] = hg
            if console is not None and yields:
                fmin, ymin = min(yields, key=lambda p: p[1])
                fmax, ymax = max(yields, key=lambda p: p[1])
                console.print(
                    f"  morph '{mname}' in '{cat.name}': yield "
                    f"{ymin:.1f} (f={fmin:g}) .. {ymax:.1f} (f={fmax:g})"
                )
        templates[cat.name] = t

    cats = [c.name for c in fit.categories]
    background_names = [b for b in backgrounds if any(b in templates[c] for c in cats)]
    return templates, signal_names, background_names


# ------------------------------------------------------------- writers


def write_shapes(path: Path, templates: dict[str, dict[str, Any]]) -> None:
    import uproot

    with uproot.recreate(path) as f:
        for bin_name, by_name in templates.items():
            for name, h1 in by_name.items():
                clean = h1.copy()
                flow = clean.view(flow=True)
                for field in ("value", "variance"):
                    flow[field][0] = 0.0
                    flow[field][-1] = 0.0
                f[f"{bin_name}/{name}"] = clean


def _rename_templates(
    templates: dict[str, dict[str, Any]], process_map: dict[str, str]
) -> dict[str, dict[str, Any]]:
    """Return a shallow template map with datacard process names remapped."""
    if not process_map:
        return templates
    mapped: dict[str, dict[str, Any]] = {}
    for bin_name, by_name in templates.items():
        mapped[bin_name] = {
            process_map.get(name, name): h1 for name, h1 in by_name.items()
        }
    return mapped


def stage_export_shapes(fitdir: Path, fit: FitConfig, templates: dict[str, dict[str, Any]],
                        console=None) -> None:
    """Stage shapes for an external workflow declared in fit.export."""
    if fit.export is None or fit.export.stage_dir is None:
        return
    stage_dir = Path(fit.export.stage_dir)
    if not stage_dir.is_absolute():
        stage_dir = util.repo_root() / stage_dir
    stage_dir.mkdir(parents=True, exist_ok=True)
    out = stage_dir / fit.export.output_file
    staged_templates = _rename_templates(templates, fit.export.process_map)
    write_shapes(out, staged_templates)
    if fit.export.write_manifest:
        manifest = {
            "target": fit.export.target,
            "source_fit_dir": str(fitdir),
            "shapes": str(out),
            "categories": list(staged_templates),
            "templates": {cat: sorted(by_name) for cat, by_name in staged_templates.items()},
            "process_map": fit.export.process_map,
        }
        (stage_dir / "wham_export_manifest.json").write_text(
            json.dumps(manifest, indent=2), encoding="utf-8"
        )
    if console is not None:
        console.print(f"  [green]staged[/green] external shapes -> {out}")


def staged_export_path(fit: FitConfig) -> Path | None:
    if fit.export is None or fit.export.stage_dir is None:
        return None
    stage_dir = Path(fit.export.stage_dir)
    if not stage_dir.is_absolute():
        stage_dir = util.repo_root() / stage_dir
    return stage_dir / fit.export.output_file


def write_datacard(
    path: Path,
    *,
    fit: FitConfig,
    templates: dict[str, dict[str, Any]],
    signal_names: list[str],
    background_names: list[str],
    parents: dict[str, str] | None = None,
    shape_affected_map: dict[str, set[str]] | None = None,
    categories: list[str] | None = None,
) -> None:
    """Multi-bin datacard: one column per (category, process present there).
    `categories` restricts the card to a subset of bins — used for the
    control card of a split (CH morph + control bins) fit, with
    signal_names=[] so every control process gets a positive (background) id."""
    parents = parents or {}
    cats = categories if categories is not None else [c.name for c in fit.categories]
    order = signal_names + background_names
    # process ids: model templates get 0, -1, ...; backgrounds 1..N
    ids = {n: -i for i, n in enumerate(signal_names)}
    ids.update({n: i for i, n in enumerate(background_names, start=1)})

    columns = [(c, n) for c in cats for n in order if n in templates[c]]
    rates = [templates[c][n].view()["value"].sum() for c, n in columns]

    width = max(12, *(len(n) + 2 for _, n in columns), *(len(c) + 2 for c in cats))

    def row(label: str, kind: str, cells: list[str]) -> str:
        return f"{label:<22}{kind:<8}" + "".join(f"{c:<{width}}" for c in cells)

    def allowed(syst, cat: str) -> bool:
        return syst.categories is None or cat in syst.categories

    lines = [
        f"# wham {__version__} | fit '{fit.name}' | POIs {', '.join(all_pois(fit))}",
        f"imax {len(cats)}  number of categories",
        "jmax *  number of processes minus 1",
        "kmax *  number of nuisance parameters",
        "-" * 80,
        # NB: text2workspace substitutes $CHANNEL (not CombineHarvester's $BIN)
        f"shapes * * {SHAPES_FILE} $CHANNEL/$PROCESS $CHANNEL/$PROCESS_$SYSTEMATIC",
        "-" * 80,
        row("bin", "", cats),
        row("observation", "",
            [f"{templates[c]['data_obs'].view()['value'].sum():.4f}" for c in cats]),
        "-" * 80,
        row("bin", "", [c for c, _ in columns]),
        row("process", "", [n for _, n in columns]),
        row("process", "", [str(ids[n]) for _, n in columns]),
        row("rate", "", [f"{r:.4f}" for r in rates]),
        "-" * 80,
    ]

    for syst in fit.systematics:
        if syst.effect == "lnN":
            cells = [
                f"{syst.scaleFactor:g}"
                if allowed(syst, c) and syst_matches(syst.processes, n, parents.get(n))
                else "-"
                for c, n in columns
            ]
        elif syst.effect == "shape":
            affected = (shape_affected_map or {}).get(syst.name, set())
            cells = [
                "1" if allowed(syst, c) and parents.get(n, n) in affected else "-"
                for c, n in columns
            ]
        else:
            continue
        # a systematic scoped away from every bin of this card (e.g. a
        # main-bin nuisance on the control card) would be an all-dash row
        if any(c != "-" for c in cells):
            lines.append(row(syst.name, syst.effect, cells))

    # rateParam: free normalization parameters, one line per matching
    # (bin, process); the shared name makes them one parameter in combine
    for syst in fit.systematics:
        if syst.effect != "rateParam":
            continue
        bounds = f" [{syst.range[0]:g},{syst.range[1]:g}]" if syst.range else ""
        for c, n in columns:
            if allowed(syst, c) and syst_matches(syst.processes, n, parents.get(n)):
                lines.append(f"{syst.name} rateParam {c} {n} {syst.init:g}{bounds}")

    # autoMCStats builds a per-bin stat model that calls getXVar() on every
    # process pdf; the external RooMomentMorph used for TES morphing lacks that
    # combine method, so it is incompatible — skip it when the CARD contains
    # morph bins. A control card of a morph fit has none (its bins are plain
    # TH1 channels merged in by combineCards.py), so it keeps autoMCStats.
    morph_bins = {b for m in fit.model.morphs.values() for b in m.categories}
    if fit.auto_mc_stats is not None and not (set(cats) & morph_bins):
        lines.append(f"* autoMCStats {fit.auto_mc_stats}")

    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def merge_command(fit: FitConfig) -> str:
    """combineCards.py merge of the CH morph card with the control card.
    The '.=' labels keep the original bin names (combineCards uses the child
    card's own bin names when the label is '.'), so render/fitsummary lookups
    by category name keep working; allowNoSignal is hard-enabled inside
    combineCards, so the backgrounds-only control card merges cleanly. Both
    cards sit next to shapes.root/ch_shapes.root in the scratch cwd, keeping
    the relative shape paths valid for text2workspace."""
    return (f"combineCards.py .={HARVEST_CARD_FILE} .={CONTROL_CARD_FILE} "
            f"> {DATACARD_FILE}")


def export_key(fit: FitConfig, input_hist_keys: dict) -> str:
    return util.short_key(
        {
            "fit": fit.model_dump(mode="json"),
            "hists": {"/".join(map(str, k)): v for k, v in sorted(input_hist_keys.items())},
            "version": __version__,
            # the combine invocations themselves: option changes (e.g. a scan
            # window or minimizer tolerance) must retrigger the run
            "commands": [fitdiag_command(fit)]
            + [scan_command(fit, s) for s in fit.resolved_scans()]
            # conditional so morph-only fits keep their existing keys
            + ([merge_command(fit)] if control_categories(fit) else []),
        }
    )


